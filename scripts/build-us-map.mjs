// Builds frontend/data/us-states.ts: an SVG outline for every state (plus DC), already projected
// with the Albers USA layout (Alaska and Hawaii moved into the corner), and each state's
// geographic center for estimating sun angles.
//
// You only need this to regenerate the map. Run it from a scratch folder that has the three packages:
//   npm i us-atlas@3.0.1 topojson-client@3.1.0 d3-geo@3.1.1
//   node /path/to/scripts/build-us-map.mjs /path/to/frontend/data/us-states.ts
// Shapes: U.S. Census Bureau cartographic boundaries (public domain), via the us-atlas package (ISC).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoAlbersUsa, geoCentroid, geoPath } from "d3-geo";

const require = createRequire(`${process.cwd()}/`);
const topo = JSON.parse(readFileSync(require.resolve("us-atlas/states-10m.json"), "utf8"));
const states = feature(topo, topo.objects.states).features;

const WIDTH = 975;
const HEIGHT = 610;
const projection = geoAlbersUsa().scale(1300).translate([WIDTH / 2, HEIGHT / 2]);
const path = geoPath(projection).digits(1); // one decimal is sharp enough on screen and keeps the file small

const out = states
  .map((s) => {
    const [lon, lat] = geoCentroid(s);
    return { fips: s.id, name: s.properties.name, d: path(s), lat: +lat.toFixed(2), lon: +lon.toFixed(2) };
  })
  .filter((s) => s.d) // drops territories the Albers USA layout doesn't place
  .sort((a, b) => a.name.localeCompare(b.name));

const file = `// Generated by scripts/build-us-map.mjs. Don't edit by hand.
// U.S. state outlines (Albers USA layout, ${WIDTH}×${HEIGHT}) and each state's geographic center.
// Source: U.S. Census Bureau cartographic boundaries (public domain), via us-atlas 3.0.1.
export type StateShape = { fips: string; name: string; d: string; lat: number; lon: number };

export const MAP_SIZE = { width: ${WIDTH}, height: ${HEIGHT} };

export const STATE_SHAPES: StateShape[] = ${JSON.stringify(out)};
`;
writeFileSync(process.argv[2], file);
console.log(`${out.length} states written to ${process.argv[2]} (${(file.length / 1024).toFixed(0)} KB)`);
